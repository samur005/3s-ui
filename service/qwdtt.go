package service

import (
	"encoding/json"
	"strings"

	"github.com/samur005/3s-ui/logger"
	"github.com/samur005/3s-ui/qwdtt"
	"github.com/samur005/3s-ui/util/common"
)

// QwdttService is the panel-side glue around the qwdtt package: it applies a
// saved configuration to the running server and the core, and resolves what
// share links should say.
type QwdttService struct {
	SettingService
}

// QwdttView is everything the qWDTT page shows.
type QwdttView struct {
	Config qwdtt.Config `json:"config"`
	Status qwdtt.Status `json:"status"`
	// Link is the share link with the host resolved; "" until a peer host and
	// password are known.
	Link string `json:"link"`
	// ResolvedHost is the host:port the link carries, whether it was typed in
	// or detected.
	ResolvedHost string `json:"resolvedHost"`
	// Hashes is the stored list split up, with no liveness attached; the page
	// asks for that separately because it is a round trip to VK per hash.
	Hashes []string `json:"hashes"`
	// HashSource says where the hashes come from: "env", "panel" (generated by
	// the panel) or "manual".
	HashSource string `json:"hashSource"`
}

// resolveHost fills an empty SubHost from the subscription domain, the panel
// domain, or the host's outbound IPv4 address, in that order.
func (s *QwdttService) resolveHost(cfg qwdtt.Config) qwdtt.Config {
	if strings.TrimSpace(cfg.SubHost) != "" {
		return cfg
	}
	for _, get := range []func() (string, error){s.SettingService.GetSubDomain, s.SettingService.GetWebDomain} {
		if h, err := get(); err == nil && strings.TrimSpace(h) != "" {
			return cfg.WithPeerHost(h)
		}
	}
	return cfg.WithPeerHost(qwdtt.DetectOutboundIPv4())
}

// View assembles the page state.
func (s *QwdttService) View() (*QwdttView, error) {
	cfg, err := qwdtt.Load()
	if err != nil {
		return nil, err
	}
	if cfg.Enabled && strings.TrimSpace(cfg.Password) == "" {
		if saved, err := qwdtt.Save(cfg); err == nil {
			cfg = saved
		}
	}
	resolved := s.resolveHost(cfg)
	v := &QwdttView{
		Config:       cfg,
		Status:       qwdtt.Get().Status(cfg),
		Link:         resolved.ClientURI(),
		ResolvedHost: resolved.SubHost,
		Hashes:       qwdtt.ParseHashes(cfg.EffectiveHashes()),
		HashSource:   "manual",
	}
	switch {
	case v.Status.HashEnv:
		v.HashSource = "env"
	case len(v.Hashes) == 0:
		v.HashSource = ""
	}
	return v, nil
}

// Save stores a configuration from the page and applies it: the server is
// reconciled, the core is restarted when the TUN inbound it needs changed, and
// a hash is generated when there is none and cookies are available.
func (s *QwdttService) Save(raw string) error {
	// Decoded over the stored configuration, so a field the caller leaves out
	// keeps its value instead of becoming a zero (autoVkHash would turn off).
	in, err := qwdtt.Load()
	if err != nil {
		return err
	}
	if err := json.Unmarshal([]byte(raw), &in); err != nil {
		return common.NewError("invalid qwdtt config: ", err.Error())
	}
	cfg, err := qwdtt.Save(in)
	if err != nil {
		return err
	}
	s.afterChange(cfg)
	return nil
}

func (s *QwdttService) afterChange(cfg qwdtt.Config) {
	var cs ConfigService
	if qwdtt.CoreNeedsRestart(cfg) && cs.CoreRunning() {
		cs.requestRestart()
	}
	if cfg.Enabled {
		if _, err := qwdtt.EnsureHashesNow(); err != nil {
			logger.Warning("qwdtt: creating a VK hash: ", err)
		}
	}
	qwdtt.Get().Reconcile()
}

// SaveCookies stores VK cookies and, when qWDTT is on with no hash yet, makes
// one straight away.
func (s *QwdttService) SaveCookies(raw string) error {
	if err := qwdtt.SaveCookies(raw); err != nil {
		return err
	}
	if cfg, err := qwdtt.Load(); err == nil && cfg.Enabled {
		if _, err := qwdtt.EnsureHashesNow(); err != nil {
			logger.Warning("qwdtt: creating a VK hash: ", err)
		}
	}
	return nil
}

// Generate creates a VK call and adds its hash.
func (s *QwdttService) Generate(replaceOldest bool) (string, error) {
	_, call, err := qwdtt.GenerateHash(replaceOldest)
	if err != nil {
		return "", err
	}
	return call.Hash, nil
}

// ClientLink is the qwdtt:// link for one client, "" when qWDTT is off or the
// client has no access to it.
func (s *QwdttService) ClientLink(clientName string) string {
	cfg, err := qwdtt.Load()
	if err != nil || !cfg.Enabled || !cfg.HasAccess(clientName) {
		return ""
	}
	return s.resolveHost(cfg).ClientURI()
}

// SubscriptionJSON is the import document for the qWDTT Android client.
func (s *QwdttService) SubscriptionJSON() (string, error) {
	cfg, err := qwdtt.Load()
	if err != nil {
		return "", err
	}
	sub, err := s.resolveHost(cfg).Subscription()
	if err != nil {
		return "", err
	}
	b, err := json.MarshalIndent(sub, "", "  ")
	return string(b), err
}
