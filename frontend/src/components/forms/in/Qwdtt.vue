<template>
  <div>
    <SectionLabel style="margin-bottom: 12px;">qWDTT</SectionLabel>
    <MHint style="margin-bottom: 14px;">{{ $t('qwdtt.serverDesc') }}</MHint>

    <div v-if="status && status.supported === false" class="note warn">{{ $t('qwdtt.linuxOnly') }}</div>
    <div v-else-if="status && status.enabled && !status.binaryFound" class="note warn">
      {{ $t('qwdtt.binaryMissing', { path: status.binary }) }}
    </div>
    <div v-else-if="status && status.enabled && status.error" class="note warn">{{ status.error }}</div>
    <div v-if="status && status.running" style="margin-bottom: 12px; display: flex; gap: 8px; flex-wrap: wrap;">
      <Chip color="emerald" dot>{{ $t('qwdtt.running') }}</Chip>
      <Chip v-if="data.routeThroughCore" :color="status.routed ? 'emerald' : 'amber'">
        {{ status.routed ? $t('qwdtt.routed') : $t('qwdtt.notRouted') }}
      </Chip>
    </div>

    <Field :label="$t('qwdtt.remark')">
      <input class="input" v-model="data.remark" placeholder="qWDTT" />
    </Field>
    <div class="grid2">
      <Field :label="$t('qwdtt.listenAddr')" :hint="$t('qwdtt.listenAddrHint')">
        <input class="input mono" v-model="data.listenAddr" placeholder="0.0.0.0:56000" />
      </Field>
      <Field :label="$t('qwdtt.wgPort')" :hint="$t('qwdtt.wgPortHint')">
        <input class="input mono" type="number" min="1" max="65535" v-model.number="data.wgPort" />
      </Field>
    </div>
    <div class="grid2">
      <Field :label="$t('qwdtt.password')" :hint="$t('qwdtt.passwordHint')">
        <input class="input mono" v-model="data.password" :placeholder="$t('qwdtt.autoGenerated')" />
      </Field>
      <Field :label="$t('qwdtt.dns')" :hint="$t('qwdtt.dnsHint')">
        <input class="input mono" v-model="data.dns" placeholder="8.8.8.8" />
      </Field>
    </div>
    <div class="grid2">
      <Field :label="$t('qwdtt.userMode')" :hint="$t('qwdtt.userModeHint')">
        <Select v-model="data.userMode">
          <option value="perClient">{{ $t('qwdtt.userModePerClient') }}</option>
          <option value="shared">{{ $t('qwdtt.userModeShared') }}</option>
        </Select>
      </Field>
      <Field v-if="data.userMode !== 'shared'" :label="$t('qwdtt.maxDevices')" :hint="$t('qwdtt.maxDevicesHint')">
        <input class="input mono" type="number" min="0" max="100" v-model.number="data.maxDevices" />
      </Field>
    </div>
    <Field :label="$t('qwdtt.subHost')" :hint="$t('qwdtt.subHostHint')">
      <input class="input mono" v-model="data.subHost" placeholder="example.com:56000" />
    </Field>
    <div class="grid2">
      <Field :label="$t('qwdtt.clientPort')" :hint="$t('qwdtt.clientPortHint')">
        <input class="input mono" type="number" min="1" max="65535" v-model.number="data.clientPort" />
      </Field>
      <Field :label="$t('qwdtt.workers')" :hint="$t('qwdtt.workersHint')">
        <input class="input mono" type="number" min="1" max="64" v-model.number="data.workers" />
      </Field>
    </div>
    <div class="grid2">
      <Field :label="$t('qwdtt.listenRaw')" :hint="$t('qwdtt.listenRawHint')">
        <input class="input mono" v-model="data.listenRaw" placeholder="0.0.0.0:56003" />
      </Field>
      <Field :label="$t('qwdtt.listenDirect')" :hint="$t('qwdtt.listenDirectHint')">
        <input class="input mono" v-model="data.listenDirect" :placeholder="$t('ui.none')" />
      </Field>
    </div>
    <Field :label="$t('qwdtt.configDir')" :hint="$t('qwdtt.configDirHint')">
      <input class="input mono" v-model="data.configDir" placeholder="db/qwdtt" />
    </Field>

    <hr class="form-divider" />
    <SectionLabel style="margin-bottom: 12px;">{{ $t('qwdtt.routing') }}</SectionLabel>
    <div style="margin-bottom: 12px;">
      <SwitchLabel v-model="data.routeThroughCore" :label="$t('qwdtt.routeThroughCore')" />
      <MHint style="margin-top: 4px;">{{ $t('qwdtt.routeThroughCoreDesc') }}</MHint>
    </div>
    <Field v-if="data.routeThroughCore" :label="$t('qwdtt.outboundTag')" :hint="$t('qwdtt.outboundTagHint')">
      <Select v-model="data.outboundTag">
        <option value="">{{ $t('qwdtt.byRules') }}</option>
        <option v-for="o in outboundTags" :key="o" :value="o">{{ o }}</option>
      </Select>
    </Field>

    <hr class="form-divider" />
    <SectionLabel style="margin-bottom: 12px;">{{ $t('qwdtt.vk') }}</SectionLabel>
    <div v-if="status && status.hashEnv" class="note warn">{{ $t('qwdtt.hashEnv') }}</div>
    <Field :label="$t('qwdtt.hashes')" :hint="$t('qwdtt.hashesHint')">
      <input class="input mono" v-model="data.vkHashes" :disabled="status && status.hashEnv" placeholder="hash1,hash2" />
    </Field>
    <div style="margin-bottom: 12px;">
      <SwitchLabel v-model="data.autoVkHash" :label="$t('qwdtt.autoHash')" />
      <MHint style="margin-top: 4px;">{{ $t('qwdtt.autoHashDesc') }}</MHint>
    </div>
    <div style="display: flex; gap: 8px; align-items: center; flex-wrap: wrap; margin-bottom: 8px;">
      <Chip v-if="status && status.hasCookies" color="emerald" dot>{{ $t('qwdtt.cookiesStored') }}</Chip>
      <Chip v-else-if="status && status.hasRemote" color="emerald" dot>{{ $t('qwdtt.remoteSet') }}</Chip>
      <Chip v-else>{{ $t('qwdtt.cookiesNone') }}</Chip>
      <Btn sm :loading="generating" :disabled="isNew || !status || !(status.hasCookies || status.hasRemote) || status.hashEnv" @click="generate">
        <Ico name="plus" :size="14" /> {{ $t('qwdtt.generate') }}
      </Btn>
      <Btn sm @click="$router.push('/qwdtt')">{{ $t('qwdtt.openPage') }}</Btn>
    </div>
    <MHint>{{ isNew ? $t('qwdtt.generateAfterSave') : $t('qwdtt.cookiesOnPage') }}</MHint>
  </div>
</template>

<script lang="ts" setup>
import { computed, onMounted, ref } from 'vue'
import Data from '@/store/modules/data'
import HttpUtils from '@/plugins/httputil'
import Field from '@/components/ui/Field.vue'
import Select from '@/components/ui/Select.vue'
import SectionLabel from '@/components/ui/SectionLabel.vue'
import SwitchLabel from '@/components/ui/SwitchLabel.vue'
import MHint from '@/components/ui/MHint.vue'
import Chip from '@/components/ui/Chip.vue'
import Btn from '@/components/ui/Btn.vue'
import Ico from '@/components/ui/Ico.vue'

const props = defineProps<{ data: any; isNew: boolean }>()

const status = ref<any>(null)
const generating = ref(false)

const outboundTags = computed((): string[] =>
  ((Data().outbounds ?? []) as any[]).map((o) => o.tag as string).filter(Boolean),
)

const loadStatus = async () => {
  const msg = await HttpUtils.get('api/qwdtt')
  if (msg.success) status.value = msg.obj?.status ?? null
  return msg
}

// The hash is stored by the server the moment it is made, so the form only has
// to pick the new list up; whatever else is being edited stays as typed.
const generate = async () => {
  generating.value = true
  try {
    const gen = await HttpUtils.post('api/qwdttGenerate', { replace: false })
    if (!gen.success) return
    const msg = await loadStatus()
    if (msg.success && msg.obj?.config) props.data.vkHashes = msg.obj.config.vkHashes
  } finally {
    generating.value = false
  }
}

onMounted(loadStatus)
</script>

<style scoped>
.note { font-size: 12.5px; padding: 8px 12px; border-radius: 10px; background: var(--surface-3); margin-bottom: 12px; color: var(--text-3); }
.note.warn { color: var(--amber); }
</style>
