<template>
  <div>
    <SectionLabel style="margin-bottom: 12px;">{{ title }}</SectionLabel>
    <MHint style="margin-bottom: 14px;">{{ $t(isAwg ? 'wg.awgDesc' : 'wg.wgDesc') }}</MHint>

    <div v-if="status && status.supported === false" class="note warn">{{ $t('wg.linuxOnly') }}</div>
    <div v-else-if="status && status.error" class="note warn">{{ status.error }}</div>
    <div v-if="status && status.running" style="margin-bottom: 12px; display: flex; gap: 8px; flex-wrap: wrap;">
      <Chip color="emerald" dot>{{ $t('wg.running') }} · {{ status.iface }}</Chip>
      <Chip>{{ $t('wg.peersOnline', { online: status.online, peers: status.peers }) }}</Chip>
      <Chip v-if="data.routeThroughCore" :color="status.routed ? 'emerald' : 'amber'">
        {{ status.routed ? $t('wg.routed') : $t('wg.notRouted') }}
      </Chip>
    </div>

    <div class="grid2">
      <Field :label="$t('wg.port')" :hint="$t('wg.portHint')">
        <input class="input mono" type="number" min="1" max="65535" v-model.number="data.listen_port" />
      </Field>
      <Field :label="$t('wg.subnet')" :hint="$t('wg.subnetHint')">
        <input class="input mono" v-model="data.subnet" :placeholder="$t('wg.autoGenerated')" />
      </Field>
    </div>
    <Field :label="$t('wg.endpoint')" :hint="$t('wg.endpointHint')">
      <input class="input mono" v-model="data.endpoint" placeholder="vpn.example.com" />
    </Field>
    <div class="grid2">
      <Field :label="$t('wg.dns')" :hint="$t('wg.dnsHint')">
        <input class="input mono" v-model="data.dns" placeholder="1.1.1.1, 8.8.8.8" />
      </Field>
      <Field :label="$t('wg.allowedIps')" :hint="$t('wg.allowedIpsHint')">
        <input class="input mono" v-model="data.allowedIps" placeholder="0.0.0.0/0, ::/0" />
      </Field>
    </div>
    <div class="grid2">
      <Field :label="$t('wg.mtu')" :hint="$t('wg.mtuHint')">
        <input class="input mono" type="number" min="0" max="1500" v-model.number="data.mtu" />
      </Field>
      <Field :label="$t('wg.keepalive')" :hint="$t('wg.keepaliveHint')">
        <input class="input mono" type="number" min="0" max="3600" v-model.number="data.keepalive" />
      </Field>
    </div>
    <Field v-if="data.publicKey" :label="$t('wg.publicKey')" :hint="$t('wg.publicKeyHint')">
      <input class="input mono" :value="data.publicKey" readonly @focus="($event.target as HTMLInputElement).select()" />
    </Field>

    <slot name="obfuscation" />

    <hr class="form-divider" />
    <SectionLabel style="margin-bottom: 12px;">{{ $t('wg.routing') }}</SectionLabel>
    <div style="margin-bottom: 12px;">
      <SwitchLabel v-model="data.routeThroughCore" :label="$t('wg.routeThroughCore')" />
      <MHint style="margin-top: 4px;">{{ $t('wg.routeThroughCoreDesc') }}</MHint>
    </div>
    <Field v-if="data.routeThroughCore" :label="$t('wg.outboundTag')" :hint="$t('wg.outboundTagHint')">
      <Select v-model="data.outboundTag">
        <option value="">{{ $t('wg.byRules') }}</option>
        <option v-for="o in outboundTags" :key="o" :value="o">{{ o }}</option>
      </Select>
    </Field>
    <MHint v-if="!isNew" style="margin-bottom: 12px;">{{ $t('wg.clientsHint') }}</MHint>
    <MHint v-if="isNew">{{ $t('wg.firewallHint') }}</MHint>
  </div>
</template>

<script lang="ts" setup>
import { computed, onMounted, ref } from 'vue'
import Data from '@/store/modules/data'
import HttpUtils from '@/plugins/httputil'
import Field from '@/components/ui/Field.vue'
import Select from '@/components/ui/Select.vue'
import SectionLabel from '@/components/ui/SectionLabel.vue'
import SwitchLabel from '@/components/ui/SwitchLabel.vue'
import MHint from '@/components/ui/MHint.vue'
import Chip from '@/components/ui/Chip.vue'

const props = defineProps<{ data: any; isNew: boolean; isAwg?: boolean }>()

const status = ref<any>(null)

const title = computed(() => (props.isAwg ? 'AmneziaWG' : 'WireGuard'))
const outboundTags = computed((): string[] =>
  ((Data().outbounds ?? []) as any[]).map((o) => o.tag as string).filter(Boolean),
)

const loadStatus = async () => {
  if (props.isNew || !props.data.id) return
  const msg = await HttpUtils.get('api/wgStatus', { id: props.data.id })
  if (msg.success) status.value = msg.obj ?? null
}

// A new inbound starts on the first UDP port no other WireGuard/AmneziaWG
// inbound has taken, so adding a second one does not collide on save.
const pickPort = () => {
  const taken = new Set(
    ((Data().inbounds ?? []) as any[])
      .filter((i) => i.type === 'wg' || i.type === 'awg')
      .map((i) => Number(i.listen_port)),
  )
  let port = 51820
  while (taken.has(port) && port < 65535) port++
  props.data.listen_port = port
}

onMounted(() => {
  if (props.isNew) pickPort()
  loadStatus()
})
</script>

<style scoped>
.note { font-size: 12.5px; padding: 8px 12px; border-radius: 10px; background: var(--surface-3); margin-bottom: 12px; color: var(--text-3); }
.note.warn { color: var(--amber); }
</style>
