<template>
  <div class="page-stack-lg fade-up" style="max-width: 1040px;">
    <!-- header: state + actions -->
    <div class="head-row">
      <div style="display: flex; align-items: center; gap: 8px; flex-wrap: wrap; flex: 1 1 auto; min-width: 0;">
        <Chip v-if="!status.supported" color="amber">{{ $t('qwdtt.linuxOnly') }}</Chip>
        <template v-else>
          <Chip v-if="status.running" color="emerald" dot>{{ $t('qwdtt.running') }}</Chip>
          <Chip v-else-if="status.enabled" color="rose" dot>{{ $t('qwdtt.stopped') }}</Chip>
          <Chip v-else>{{ $t('qwdtt.off') }}</Chip>
          <Chip v-if="status.running && cfg.routeThroughCore" :color="status.routed ? 'emerald' : 'amber'">
            {{ status.routed ? $t('qwdtt.routed') : $t('qwdtt.notRouted') }}
          </Chip>
          <Chip v-if="status.running">pid {{ status.pid }} · {{ uptime }}</Chip>
        </template>
      </div>
      <div class="head-actions">
        <Btn variant="primary" sm :loading="saving" :disabled="!dirty" @click="save">
          <Ico name="check" :size="15" /> {{ $t('actions.save') }}
        </Btn>
        <Btn sm :loading="restarting" :disabled="dirty || !cfg.enabled" @click="restart">
          <Ico name="refresh" :size="15" /> {{ $t('qwdtt.restart') }}
        </Btn>
      </div>
    </div>

    <div v-if="status.enabled && status.error" class="fieldnote warn">
      <span>{{ status.error }}</span>
    </div>
    <div v-if="status.enabled && status.supported && !status.binaryFound" class="fieldnote warn">
      <span>{{ $t('qwdtt.binaryMissing', { path: status.binary }) }}</span>
    </div>

    <!-- ===================== settings ===================== -->
    <SettingsGroup :title="$t('qwdtt.server')" :desc="$t('qwdtt.serverDesc')" grid>
      <ToggleRow class="sg-span" v-model="cfg.enabled" :label="$t('qwdtt.enable')" :desc="$t('qwdtt.enableDesc')" />
      <SRow :label="$t('qwdtt.remark')">
        <input class="input" v-model="cfg.remark" placeholder="qWDTT" />
      </SRow>
      <SRow :label="$t('qwdtt.listenAddr')" :hint="$t('qwdtt.listenAddrHint')">
        <input class="input mono" v-model="cfg.listenAddr" placeholder="0.0.0.0:56000" />
      </SRow>
      <SRow :label="$t('qwdtt.wgPort')" :hint="$t('qwdtt.wgPortHint')">
        <input class="input mono" type="number" min="1" max="65535" v-model.number="cfg.wgPort" />
      </SRow>
      <SRow :label="$t('qwdtt.password')" :hint="$t('qwdtt.passwordHint')">
        <input class="input mono" v-model="cfg.password" :placeholder="$t('qwdtt.autoGenerated')" />
      </SRow>
      <SRow :label="$t('qwdtt.dns')" :hint="$t('qwdtt.dnsHint')">
        <input class="input mono" v-model="cfg.dns" placeholder="8.8.8.8" />
      </SRow>
      <SRow :label="$t('qwdtt.subHost')" :hint="$t('qwdtt.subHostHint')">
        <input class="input mono" v-model="cfg.subHost" :placeholder="resolvedHost || 'example.com:56000'" />
      </SRow>
      <SRow :label="$t('qwdtt.clientPort')" :hint="$t('qwdtt.clientPortHint')">
        <input class="input mono" type="number" min="1" max="65535" v-model.number="cfg.clientPort" />
      </SRow>
      <SRow :label="$t('qwdtt.workers')" :hint="$t('qwdtt.workersHint')">
        <input class="input mono" type="number" min="1" max="64" v-model.number="cfg.workers" />
      </SRow>
      <SRow :label="$t('qwdtt.listenRaw')" :hint="$t('qwdtt.listenRawHint')">
        <input class="input mono" v-model="cfg.listenRaw" placeholder="0.0.0.0:56003" />
      </SRow>
      <SRow :label="$t('qwdtt.listenDirect')" :hint="$t('qwdtt.listenDirectHint')">
        <input class="input mono" v-model="cfg.listenDirect" :placeholder="$t('ui.none')" />
      </SRow>
      <SRow :label="$t('qwdtt.configDir')" :hint="$t('qwdtt.configDirHint')">
        <input class="input mono" v-model="cfg.configDir" placeholder="db/qwdtt" />
      </SRow>
    </SettingsGroup>

    <SettingsGroup :title="$t('qwdtt.routing')" :desc="$t('qwdtt.routingDesc')" grid>
      <ToggleRow class="sg-span" v-model="cfg.routeThroughCore" :label="$t('qwdtt.routeThroughCore')"
                 :desc="$t('qwdtt.routeThroughCoreDesc')" />
      <SRow v-if="cfg.routeThroughCore" :label="$t('qwdtt.outboundTag')" :hint="$t('qwdtt.outboundTagHint')">
        <Select v-model="cfg.outboundTag">
          <option value="">{{ $t('qwdtt.byRules') }}</option>
          <option v-for="o in outboundTags" :key="o" :value="o">{{ o }}</option>
        </Select>
      </SRow>
      <div v-if="cfg.routeThroughCore && status.running" class="sg-span fieldnote" :class="status.tunReady ? 'ok' : 'warn'">
        <span>{{ status.tunReady ? $t('qwdtt.tunReady') : $t('qwdtt.tunPending') }}</span>
      </div>
    </SettingsGroup>

    <SettingsGroup :title="$t('qwdtt.access')" :desc="$t('qwdtt.accessDesc')">
      <Segmented v-model="cfg.accessMode" :options="accessOptions" />
      <div v-if="cfg.accessMode === 'selected'" style="margin-top: 14px;">
        <ChipSelect v-model="cfg.clients" :options="clientOptions" :label="$t('qwdtt.clients')"
                    :placeholder="$t('ui.selectHint')" />
      </div>
    </SettingsGroup>

    <!-- ===================== VK hashes ===================== -->
    <SettingsGroup :title="$t('qwdtt.vk')" :desc="$t('qwdtt.vkDesc')">
      <div v-if="status.hashEnv" class="fieldnote warn" style="margin-bottom: 12px;">
        <span>{{ $t('qwdtt.hashEnv') }}</span>
      </div>

      <div class="field-grid" style="grid-template-columns: 1fr;">
        <Field :label="$t('qwdtt.hashes')" :hint="$t('qwdtt.hashesHint')" :mb="0">
          <input class="input mono" v-model="cfg.vkHashes" :disabled="status.hashEnv" placeholder="hash1,hash2" />
        </Field>
      </div>

      <div v-if="hashChecks.length" class="hash-list">
        <div v-for="h in hashChecks" :key="h.hash" class="hash-row">
          <span class="mono hash-name">{{ h.hash }}</span>
          <Chip v-if="h.alive === true" color="emerald" dot>{{ $t('qwdtt.alive') }}</Chip>
          <Chip v-else-if="h.alive === false" color="rose" dot>{{ $t('qwdtt.dead') }}</Chip>
          <Chip v-else color="amber" :title="h.error">{{ $t('qwdtt.unknown') }}</Chip>
          <Chip v-if="h.generated">{{ $t('qwdtt.generatedByPanel') }}</Chip>
        </div>
      </div>

      <div class="btn-row">
        <Btn variant="primary" sm :loading="generating" :disabled="status.hashEnv || !status.hasCookies" @click="generate(false)">
          <Ico name="plus" :size="15" /> {{ $t('qwdtt.generate') }}
        </Btn>
        <Btn sm :loading="generating" :disabled="status.hashEnv || !status.hasCookies || hashCount < 4" @click="generate(true)">
          <Ico name="refresh" :size="15" /> {{ $t('qwdtt.generateReplace') }}
        </Btn>
        <Btn sm :loading="checking" :disabled="hashCount === 0" @click="checkHashes">
          <Ico name="bolt" :size="15" /> {{ $t('qwdtt.checkHashes') }}
        </Btn>
      </div>
      <div v-if="!status.hasCookies" class="fieldnote" style="margin-top: 10px;">
        <span>{{ $t('qwdtt.needCookies') }}</span>
      </div>

      <ToggleRow v-model="cfg.autoVkHash" style="margin-top: 14px;" :label="$t('qwdtt.autoHash')"
                 :desc="$t('qwdtt.autoHashDesc')" />
    </SettingsGroup>

    <SettingsGroup :title="$t('qwdtt.cookies')" :desc="$t('qwdtt.cookiesDesc')">
      <div style="display: flex; align-items: center; gap: 8px; margin-bottom: 10px;">
        <Chip v-if="status.hasCookies" color="emerald" dot>{{ $t('qwdtt.cookiesStored') }}</Chip>
        <Chip v-else>{{ $t('qwdtt.cookiesNone') }}</Chip>
        <Chip v-if="cookiesOk === true" color="emerald">{{ $t('qwdtt.cookiesValid') }}</Chip>
        <Chip v-else-if="cookiesOk === false" color="rose" :title="cookiesErr">{{ $t('qwdtt.cookiesInvalid') }}</Chip>
      </div>
      <textarea class="input mono" rows="5" v-model="cookiesText" spellcheck="false" autocomplete="off"
                :placeholder="$t('qwdtt.cookiesPlaceholder')" />
      <div class="btn-row">
        <Btn variant="primary" sm :loading="cookieBusy" :disabled="!cookiesText.trim()" @click="saveCookies">
          <Ico name="check" :size="15" /> {{ $t('qwdtt.cookiesSave') }}
        </Btn>
        <Btn sm :loading="cookieBusy" :disabled="!status.hasCookies" @click="checkCookies">
          <Ico name="bolt" :size="15" /> {{ $t('qwdtt.cookiesCheck') }}
        </Btn>
        <Btn sm :loading="cookieBusy" :disabled="!status.hasCookies" style="color: var(--rose);" @click="clearCookies">
          <Ico name="trash" :size="15" /> {{ $t('qwdtt.cookiesClear') }}
        </Btn>
      </div>
    </SettingsGroup>

    <!-- ===================== share ===================== -->
    <SettingsGroup :title="$t('qwdtt.share')" :desc="$t('qwdtt.shareDesc')">
      <template v-if="link">
        <div class="share-grid">
          <div class="qr-box"><QrcodeVue :value="link" :size="180" level="M" render-as="svg" background="#ffffff" foreground="#000000" /></div>
          <div style="flex: 1; min-width: 0;">
            <textarea class="input mono" rows="5" readonly :value="link" @focus="($event.target as HTMLTextAreaElement).select()" />
            <div class="btn-row">
              <Btn sm @click="copyToClipboard(link)"><Ico name="copy" :size="15" /> {{ $t('copyToClipboard') }}</Btn>
              <Btn sm @click="showSubscription"><Ico name="list" :size="15" /> {{ $t('qwdtt.subscriptionJson') }}</Btn>
            </div>
            <div v-if="dirty" class="fieldnote" style="margin-top: 10px;"><span>{{ $t('qwdtt.saveToUpdateLink') }}</span></div>
          </div>
        </div>
        <textarea v-if="subscriptionDoc" class="input mono" rows="12" readonly :value="subscriptionDoc" style="margin-top: 12px;" />
      </template>
      <div v-else class="fieldnote"><span>{{ $t('qwdtt.noLink') }}</span></div>
    </SettingsGroup>

    <!-- ===================== log ===================== -->
    <SettingsGroup :title="$t('qwdtt.log')">
      <div class="btn-row" style="margin-top: 0;">
        <Btn sm :loading="logLoading" @click="loadLogs"><Ico name="refresh" :size="15" /> {{ $t('qwdtt.refresh') }}</Btn>
      </div>
      <pre v-if="logs.length" class="log-box">{{ logs.join('\n') }}</pre>
      <div v-else class="fieldnote" style="margin-top: 10px;"><span>{{ $t('qwdtt.noLogs') }}</span></div>
    </SettingsGroup>
  </div>
</template>

<script lang="ts" setup>
import { computed, onBeforeUnmount, onMounted, ref } from 'vue'
import { useI18n } from 'vue-i18n'
import QrcodeVue from 'qrcode.vue'
import Data from '@/store/modules/data'
import HttpUtils from '@/plugins/httputil'
import { copyToClipboard } from '@/plugins/clipboard'
import Btn from '@/components/ui/Btn.vue'
import Ico from '@/components/ui/Ico.vue'
import Chip from '@/components/ui/Chip.vue'
import Field from '@/components/ui/Field.vue'
import Select from '@/components/ui/Select.vue'
import Segmented from '@/components/ui/Segmented.vue'
import ChipSelect from '@/components/ui/ChipSelect.vue'
import SRow from '@/components/ui/SRow.vue'
import ToggleRow from '@/components/ui/ToggleRow.vue'
import SettingsGroup from '@/components/ui/SettingsGroup.vue'

interface QwdttConfig {
  remark: string
  enabled: boolean
  listenAddr: string
  wgPort: number
  password: string
  dns: string
  configDir: string
  listenRaw: string
  listenDirect: string
  subHost: string
  vkHashes: string
  clientPort: number
  workers: number
  autoVkHash: boolean
  routeThroughCore: boolean
  outboundTag: string
  accessMode: 'all' | 'selected'
  clients: string[]
}

interface QwdttStatus {
  supported: boolean
  enabled: boolean
  running: boolean
  pid: number
  uptime: number
  binary: string
  binaryFound: boolean
  routed: boolean
  tunReady: boolean
  error?: string
  lastExit?: string
  hashEnv: boolean
  hasCookies: boolean
}

interface HashCheck {
  hash: string
  alive: boolean | null
  generated: boolean
  error?: string
}

const { t } = useI18n({ useScope: 'global' })
const data = Data()

const blank = (): QwdttConfig => ({
  remark: '', enabled: false, listenAddr: '0.0.0.0:56000', wgPort: 56001, password: '', dns: '8.8.8.8',
  configDir: '', listenRaw: '0.0.0.0:56003', listenDirect: '', subHost: '', vkHashes: '', clientPort: 9000,
  workers: 16, autoVkHash: true, routeThroughCore: true, outboundTag: '', accessMode: 'all', clients: [],
})

const cfg = ref<QwdttConfig>(blank())
const saved = ref('')
const status = ref<QwdttStatus>({
  supported: true, enabled: false, running: false, pid: 0, uptime: 0, binary: '', binaryFound: true,
  routed: false, tunReady: false, hashEnv: false, hasCookies: false,
})
const link = ref('')
const resolvedHost = ref('')
const hashChecks = ref<HashCheck[]>([])
const logs = ref<string[]>([])
const subscriptionDoc = ref('')
const cookiesText = ref('')
const cookiesOk = ref<boolean | null>(null)
const cookiesErr = ref('')

const saving = ref(false)
const restarting = ref(false)
const generating = ref(false)
const checking = ref(false)
const cookieBusy = ref(false)
const logLoading = ref(false)

const dirty = computed(() => JSON.stringify(cfg.value) !== saved.value)
const hashCount = computed(() => cfg.value.vkHashes.split(/[,;\s]+/).filter(Boolean).length)

const accessOptions = computed((): [string, string][] => [
  ['all', t('qwdtt.accessAll')],
  ['selected', t('qwdtt.accessSelected')],
])
const clientOptions = computed(() =>
  (data.clients as any[]).map((c) => ({ title: c.name as string, value: c.name as string })),
)
const outboundTags = computed((): string[] =>
  (data.outbounds as any[]).map((o) => o.tag as string).filter(Boolean),
)

const uptime = computed(() => {
  const s = status.value.uptime
  if (s < 60) return s + 's'
  if (s < 3600) return Math.floor(s / 60) + 'm'
  if (s < 86400) return Math.floor(s / 3600) + 'h'
  return Math.floor(s / 86400) + 'd'
})

// Apply a server view. keepForm leaves the form alone: a status poll must not
// overwrite what the operator is typing.
const apply = (view: any, keepForm = false) => {
  if (!view) return
  status.value = view.status
  link.value = view.link ?? ''
  resolvedHost.value = view.resolvedHost ?? ''
  if (keepForm) {
    // The hash list changes behind the form (cron, Generate); follow it while
    // the field itself is untouched.
    if (JSON.stringify({ ...cfg.value, vkHashes: '' }) === JSON.stringify({ ...JSON.parse(saved.value), vkHashes: '' })) {
      cfg.value.vkHashes = view.config.vkHashes
      saved.value = JSON.stringify(cfg.value)
    }
    return
  }
  const c: QwdttConfig = { ...blank(), ...view.config }
  c.clients = c.clients ?? []
  cfg.value = c
  saved.value = JSON.stringify(c)
}

const load = async (keepForm = false) => {
  const msg = await HttpUtils.get('api/qwdtt')
  if (msg.success) apply(msg.obj, keepForm)
}

const save = async () => {
  saving.value = true
  const msg = await HttpUtils.post('api/qwdttSave', { config: JSON.stringify(cfg.value) })
  saving.value = false
  if (msg.success) {
    apply(msg.obj)
    subscriptionDoc.value = ''
    // The TUN inbound is added to the core a moment after a save.
    setTimeout(() => load(true), 3000)
  }
}

const restart = async () => {
  restarting.value = true
  const msg = await HttpUtils.post('api/qwdttRestart', {})
  restarting.value = false
  if (msg.success) apply(msg.obj, true)
}

const generate = async (replace: boolean) => {
  generating.value = true
  const msg = await HttpUtils.post('api/qwdttGenerate', { replace })
  generating.value = false
  if (msg.success) {
    apply(msg.obj, true)
    hashChecks.value = []
    await checkHashes()
  }
}

const checkHashes = async () => {
  checking.value = true
  const msg = await HttpUtils.post('api/qwdttHashesCheck', {})
  checking.value = false
  if (msg.success) hashChecks.value = msg.obj ?? []
}

const saveCookies = async () => {
  cookieBusy.value = true
  const msg = await HttpUtils.post('api/qwdttCookies', { cookies: cookiesText.value })
  cookieBusy.value = false
  if (msg.success) {
    cookiesText.value = ''
    cookiesOk.value = null
    apply(msg.obj, true)
    await checkCookies()
  }
}

const checkCookies = async () => {
  cookieBusy.value = true
  const msg = await HttpUtils.post('api/qwdttCookiesCheck', {})
  cookieBusy.value = false
  cookiesOk.value = msg.success
  cookiesErr.value = msg.success ? '' : msg.msg
}

const clearCookies = async () => {
  cookieBusy.value = true
  const msg = await HttpUtils.post('api/qwdttCookiesClear', {})
  cookieBusy.value = false
  if (msg.success) {
    cookiesOk.value = null
    apply(msg.obj, true)
  }
}

const showSubscription = async () => {
  const msg = await HttpUtils.get('api/qwdttSubscription')
  if (msg.success) subscriptionDoc.value = msg.obj ?? ''
}

const loadLogs = async () => {
  logLoading.value = true
  const msg = await HttpUtils.get('api/qwdttLogs', { c: 200 })
  logLoading.value = false
  if (msg.success) logs.value = msg.obj ?? []
}

let timer: ReturnType<typeof setInterval> | undefined
onMounted(async () => {
  await load()
  if (data.clients.length === 0 || data.outbounds.length === 0) data.loadData()
  loadLogs()
  timer = setInterval(() => load(true), 10000)
})
onBeforeUnmount(() => clearInterval(timer))
</script>

